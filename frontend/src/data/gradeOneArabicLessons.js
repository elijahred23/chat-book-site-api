const makeItems = (rows, category, context) => rows.map(([ar, pronunciation, en]) => ({
  ar,
  pronunciation,
  en,
  category,
  ...(context ? { context } : {}),
}));

const makeLesson = ({ id, title, summary, topic, focus, vocab, phrases, notes = [] }) => ({
  id,
  title,
  summary,
  level: "Grade 1",
  topic,
  focus,
  vocab: makeItems(vocab, topic),
  phrases: makeItems(phrases, topic, `Use this sentence when talking about ${topic.toLowerCase()}.`),
  practice: [],
  notes: [
    "Listen first, repeat three times, then say the Arabic while hiding the English.",
    ...notes,
  ],
});

